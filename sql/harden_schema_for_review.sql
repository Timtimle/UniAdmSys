-- UniAdmSys: schema hardening for project review
-- Normalizes the admission workflow and closes the most obvious integrity/security gaps.
-- Run AFTER the current candidate/special-admission scripts.

BEGIN;

-- =========================================================
-- 1) NORMALIZE SUBJECTS
-- =========================================================
CREATE TABLE IF NOT EXISTS public.mon_thi (
    ma_mon VARCHAR(20) PRIMARY KEY,
    ten_mon VARCHAR(100) NOT NULL UNIQUE
);

INSERT INTO public.mon_thi(ma_mon, ten_mon) VALUES
('TOAN','Toán'),
('VAN','Ngữ văn'),
('ANH','Tiếng Anh'),
('LY','Vật lý'),
('HOA','Hóa học'),
('SINH','Sinh học'),
('SU','Lịch sử'),
('DIA','Địa lý'),
('GDKT_PL','Giáo dục kinh tế và pháp luật')
ON CONFLICT (ma_mon) DO UPDATE SET ten_mon = EXCLUDED.ten_mon;

ALTER TABLE public.diem_thi
    ADD COLUMN IF NOT EXISTS ma_mon VARCHAR(20);

UPDATE public.diem_thi
SET ma_mon = CASE trim(mon_thi)
    WHEN 'Toán' THEN 'TOAN'
    WHEN 'Ngữ văn' THEN 'VAN'
    WHEN 'Tiếng Anh' THEN 'ANH'
    WHEN 'Vật lý' THEN 'LY'
    WHEN 'Hóa học' THEN 'HOA'
    WHEN 'Sinh học' THEN 'SINH'
    WHEN 'Lịch sử' THEN 'SU'
    WHEN 'Địa lý' THEN 'DIA'
    WHEN 'Giáo dục kinh tế và pháp luật' THEN 'GDKT_PL'
    ELSE ma_mon
END
WHERE ma_mon IS NULL
  AND to_regclass('public.diem_thi') IS NOT NULL;

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_schema='public' AND table_name='diem_thi' AND column_name='ma_mon'
    ) THEN
        ALTER TABLE public.diem_thi
            DROP CONSTRAINT IF EXISTS diem_thi_ma_mon_fkey;

        ALTER TABLE public.diem_thi
            ADD CONSTRAINT diem_thi_ma_mon_fkey
            FOREIGN KEY (ma_mon)
            REFERENCES public.mon_thi(ma_mon)
            ON DELETE RESTRICT;
    END IF;
END $$;

DROP INDEX IF EXISTS public.idx_diem_thi_unique;

CREATE UNIQUE INDEX IF NOT EXISTS idx_diem_thi_unique_mon
ON public.diem_thi(ma_thi_sinh, nam, ma_mon)
WHERE ma_mon IS NOT NULL;


-- =========================================================
-- 2) APPLICATION DOSSIER / WORKFLOW
-- One dossier per candidate per admission year.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.ho_so_xet_tuyen (
    ma_ho_so BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_thi_sinh BIGINT NOT NULL
        REFERENCES public.thi_sinh(ma_thi_sinh)
        ON DELETE CASCADE,
    nam SMALLINT NOT NULL DEFAULT 2025,
    trang_thai VARCHAR(30) NOT NULL DEFAULT 'nhap',
    ma_can_bo_phu_trach BIGINT
        REFERENCES public.can_bo(ma_can_bo)
        ON DELETE SET NULL,
    ngay_nop TIMESTAMP WITH TIME ZONE,
    ngay_duyet TIMESTAMP WITH TIME ZONE,
    ghi_chu TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    CONSTRAINT ho_so_trang_thai_check CHECK (
        trang_thai IN ('nhap','da_nop','dang_duyet','yeu_cau_bo_sung','hoan_tat')
    ),
    CONSTRAINT ho_so_thi_sinh_nam_unique UNIQUE (ma_thi_sinh, nam)
);

INSERT INTO public.ho_so_xet_tuyen(ma_thi_sinh, nam, trang_thai, ngay_nop)
SELECT DISTINCT
    nv.ma_thi_sinh,
    nv.nam,
    'da_nop',
    MIN(nv.created_at) OVER (PARTITION BY nv.ma_thi_sinh, nv.nam)
FROM public.nguyen_vong nv
ON CONFLICT (ma_thi_sinh, nam) DO NOTHING;

ALTER TABLE public.nguyen_vong
    ADD COLUMN IF NOT EXISTS ma_ho_so BIGINT;

UPDATE public.nguyen_vong nv
SET ma_ho_so = hs.ma_ho_so
FROM public.ho_so_xet_tuyen hs
WHERE hs.ma_thi_sinh = nv.ma_thi_sinh
  AND hs.nam = nv.nam
  AND nv.ma_ho_so IS NULL;

ALTER TABLE public.nguyen_vong
    DROP CONSTRAINT IF EXISTS nguyen_vong_ma_ho_so_fkey;

ALTER TABLE public.nguyen_vong
    ADD CONSTRAINT nguyen_vong_ma_ho_so_fkey
    FOREIGN KEY (ma_ho_so)
    REFERENCES public.ho_so_xet_tuyen(ma_ho_so)
    ON DELETE CASCADE;

DROP INDEX IF EXISTS public.idx_nguyen_vong_unique_order;

CREATE UNIQUE INDEX IF NOT EXISTS idx_nguyen_vong_ho_so_order
ON public.nguyen_vong(ma_ho_so, thu_tu_nguyen_vong)
WHERE ma_ho_so IS NOT NULL;


