-- =========================================================
-- 4) FLOOR SCORE BELONGS TO ADMISSION DATA, NOT TUITION
-- Safe to rerun whether the old hoc_phi.diem_san_* columns still exist or not.
-- =========================================================
CREATE TABLE IF NOT EXISTS public.nguong_dau_vao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ma_truong VARCHAR(20) NOT NULL
        REFERENCES public.truong_dh(ma_tuyen_sinh)
        ON DELETE CASCADE,
    nam SMALLINT NOT NULL DEFAULT 2025,
    ma_nganh VARCHAR(20)
        REFERENCES public.nganh(ma_nganh)
        ON DELETE CASCADE,
    ma_phuong_thuc VARCHAR(20)
        REFERENCES public.phuong_thuc_xet_tuyen(ma_phuong_thuc)
        ON DELETE SET NULL,
    diem_san_min NUMERIC(6,2),
    diem_san_max NUMERIC(6,2),
    trang_thai VARCHAR(30) DEFAULT 'chua_xac_minh',
    ghi_chu TEXT,
    source_url TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    CONSTRAINT nguong_dau_vao_range_check
        CHECK (
            diem_san_min IS NULL OR diem_san_max IS NULL
            OR diem_san_max >= diem_san_min
        )
);

DO $$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'hoc_phi'
          AND column_name = 'diem_san_min'
    ) THEN
        -- Use dynamic SQL because these legacy columns may already be gone.
        EXECUTE $sql$
            INSERT INTO public.nguong_dau_vao(
                ma_truong, nam, diem_san_min, diem_san_max,
                trang_thai, ghi_chu, source_url
            )
            SELECT
                ma_truong,
                nam,
                diem_san_min,
                diem_san_max,
                COALESCE(diem_san_trang_thai, 'chua_xac_minh'),
                diem_san_ghi_chu,
                diem_san_source_url
            FROM public.hoc_phi
            WHERE diem_san_min IS NOT NULL
               OR diem_san_max IS NOT NULL
               OR diem_san_ghi_chu IS NOT NULL
               OR diem_san_source_url IS NOT NULL
        $sql$;

        -- Views depend on the old columns, so remove them before dropping columns.
        DROP VIEW IF EXISTS public.v_catalog_tuyen_sinh_2025;
        DROP VIEW IF EXISTS public.v_truong_tuyen_sinh_2025;

        EXECUTE $sql$
            ALTER TABLE public.hoc_phi
                DROP COLUMN IF EXISTS diem_san_min,
                DROP COLUMN IF EXISTS diem_san_max,
                DROP COLUMN IF EXISTS diem_san_trang_thai,
                DROP COLUMN IF EXISTS diem_san_ghi_chu,
                DROP COLUMN IF EXISTS diem_san_source_url
        $sql$;
    END IF;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS idx_nguong_dau_vao_school_level
ON public.nguong_dau_vao(
    ma_truong,
    nam,
    COALESCE(ma_nganh,''),
    COALESCE(ma_phuong_thuc,'')
);

-- Recreate the public school/catalog views against nguong_dau_vao.
CREATE OR REPLACE VIEW public.v_truong_tuyen_sinh_2025 AS
SELECT
    t.ma_truong AS id_truong,
    t.ma_tuyen_sinh,
    t.ten_truong,

    h.hoc_phi_min,
    h.hoc_phi_max,
    h.don_vi AS hoc_phi_don_vi,
    h.trang_thai AS hoc_phi_trang_thai,
    h.source_url AS hoc_phi_source_url,

    c.chi_tieu,
    c.chi_tieu_min,
    c.chi_tieu_max,
    c.trang_thai AS chi_tieu_trang_thai,
    c.source_url AS chi_tieu_source_url,

    n.diem_san_min,
    n.diem_san_max,
    n.trang_thai AS diem_san_trang_thai,
    n.ghi_chu AS diem_san_ghi_chu,
    n.source_url AS diem_san_source_url

FROM public.truong_dh t
LEFT JOIN public.hoc_phi h
    ON h.ma_truong = t.ma_tuyen_sinh
   AND h.nam = 2025
LEFT JOIN public.chi_tieu_tuyen_sinh c
    ON c.ma_truong = t.ma_tuyen_sinh
   AND c.nam = 2025
   AND COALESCE(c.cap_do, 'truong') = 'truong'
LEFT JOIN public.nguong_dau_vao n
    ON n.ma_truong = t.ma_tuyen_sinh
   AND n.nam = 2025
   AND n.ma_nganh IS NULL
   AND n.ma_phuong_thuc IS NULL;

CREATE OR REPLACE VIEW public.v_catalog_tuyen_sinh_2025 AS
SELECT
    n.ma_nganh,
    n.ma_truong,
    n.ten_truong,
    n.ma_nganh_tuyen_sinh,
    n.ten_nganh,
    n.ma_nganh_bo,
    n.ten_nganh_bo,

    h.hoc_phi_min,
    h.hoc_phi_max,
    h.hoc_phi_don_vi,
    h.hoc_phi_trang_thai,

    h.chi_tieu,
    h.chi_tieu_min,
    h.chi_tieu_max,
    h.chi_tieu_trang_thai,

    h.diem_san_min,
    h.diem_san_max,
    h.diem_san_trang_thai,
    h.diem_san_ghi_chu,
    h.diem_san_source_url

FROM public.v_nganh_2025 n
LEFT JOIN public.v_truong_tuyen_sinh_2025 h
    ON h.ma_tuyen_sinh = n.ma_truong;


-- =========================================================
-- 5) RESULT NORMALIZATION
-- ma_nv already identifies the candidate through nguyen_vong -> ho_so.
-- Keep old ma_thi_sinh for compatibility for now, but prevent mismatch.
-- =========================================================
CREATE OR REPLACE FUNCTION public.check_ket_qua_candidate_consistency()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
    v_ma_thi_sinh BIGINT;
BEGIN
    SELECT hs.ma_thi_sinh
      INTO v_ma_thi_sinh
    FROM public.nguyen_vong nv
    LEFT JOIN public.ho_so_xet_tuyen hs ON hs.ma_ho_so = nv.ma_ho_so
    WHERE nv.ma_nv = NEW.ma_nv;

    IF v_ma_thi_sinh IS NOT NULL
       AND NEW.ma_thi_sinh IS DISTINCT FROM v_ma_thi_sinh THEN
        RAISE EXCEPTION 'ket_qua_xet_tuyen.ma_thi_sinh does not match nguyen_vong/ho_so';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_check_ket_qua_candidate
ON public.ket_qua_xet_tuyen;

CREATE TRIGGER trg_check_ket_qua_candidate
BEFORE INSERT OR UPDATE
ON public.ket_qua_xet_tuyen
FOR EACH ROW
EXECUTE FUNCTION public.check_ket_qua_candidate_consistency();


